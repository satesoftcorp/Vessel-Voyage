// Helper to generate smooth historical curve
function generateTimeline(basePrice: number, points: number, volatility: number, trend: number = 0.005) {
  const result = [];
  let current = basePrice * (1 - trend * points * 0.5);
  for (let i = 0; i < points; i++) {
    const change = (Math.random() - 0.48 + trend) * (volatility * current);
    current = Math.max(current + change, basePrice * 0.4);
    result.push({
      time: `T-${points - i}`,
      price: parseFloat(current.toFixed(2)),
      volume: Math.floor(Math.random() * 5000000 + 1000000),
    });
  }
  // Ensure last point is close to basePrice
  result[result.length - 1].price = basePrice;
  return result;
}

